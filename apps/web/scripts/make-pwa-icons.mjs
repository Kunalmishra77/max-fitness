/*
 * Every logo file the web app serves, from the gym's own logo (ADR-061).
 *
 *   node scripts/make-pwa-icons.mjs
 *
 * Source: assets/brand/max-gym-logo.png (transparent PNG). Writes
 * - public/brand/logo-{96,192,384}.{webp,png}: the logo, trimmed, for the nav and footer;
 * - src/app/icon.png (192) and src/app/apple-icon.png (180): the browser and iOS icons;
 * - public/icons/max-{192,512}.png and max-maskable-512.png: Max Register's home-screen
 *   icons. The maskable icon keeps the logo inside the middle 80% Android may crop to;
 * - src/content/og-logo.generated.ts: a small inline copy for the social share image;
 * - assets/brand/max-gym-logo-print.png: an 800px copy the QR poster embeds.
 *
 * Icons put the logo on the obsidian ground, where its white and red read best.
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, '../../../assets/brand/max-gym-logo.png');
const brandDir = resolve(here, '../public/brand');
const iconDir = resolve(here, '../public/icons');
const appDir = resolve(here, '../src/app');
const OBSIDIAN = '#0A0A0B';

const logo = await sharp(await readFile(source)).trim({ threshold: 1 }).png().toBuffer();
const { width, height } = await sharp(logo).metadata();
await mkdir(brandDir, { recursive: true });
await mkdir(iconDir, { recursive: true });

const report = [`logo trimmed to ${width}x${height}`];

for (const size of [96, 192, 384]) {
  const resized = sharp(logo).resize({ height: size, withoutEnlargement: true });
  await resized.clone().webp({ quality: 90, alphaQuality: 90 }).toFile(resolve(brandDir, `logo-${size}.webp`));
  await resized.clone().png({ compressionLevel: 9, palette: true, quality: 90 }).toFile(resolve(brandDir, `logo-${size}.png`));
  report.push(`public/brand/logo-${size}`);
}

/** The logo centred on obsidian, taking `share` of the square. */
async function onGround(size, share) {
  const inner = Math.round(size * share);
  const mark = await sharp(logo).resize(inner, inner, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } }).png().toBuffer();
  return sharp({ create: { width: size, height: size, channels: 4, background: OBSIDIAN } })
    .composite([{ input: mark, top: Math.round((size - inner) / 2), left: Math.round((size - inner) / 2) }])
    // A palette PNG: the logo has few colours, and the favicon is fetched on every first visit.
    .png({ compressionLevel: 9, palette: true, quality: 90 })
    .toBuffer();
}

await writeFile(resolve(appDir, 'icon.png'), await onGround(192, 0.9));
await writeFile(resolve(appDir, 'apple-icon.png'), await onGround(180, 0.86));
await writeFile(resolve(iconDir, 'max-192.png'), await onGround(192, 0.9));
await writeFile(resolve(iconDir, 'max-512.png'), await onGround(512, 0.9));
await writeFile(resolve(iconDir, 'max-maskable-512.png'), await onGround(512, 0.66));
report.push('src/app/icon.png, src/app/apple-icon.png, public/icons/*');

// The share image is rendered on the server, where public/ is not on disk: inline a small copy.
const ogLogo = await sharp(logo).resize({ height: 200 }).png({ compressionLevel: 9, palette: true, quality: 90 }).toBuffer();
await writeFile(
  resolve(here, '../src/content/og-logo.generated.ts'),
  `// Generated by scripts/make-pwa-icons.mjs — do not edit.
export const OG_LOGO_SRC = 'data:image/png;base64,${ogLogo.toString('base64')}';
`,
);
report.push(`src/content/og-logo.generated.ts ${ogLogo.length} bytes`);

// The QR poster embeds the logo; 800px is sharp at 9 cm and keeps the SVG light.
await sharp(logo).resize({ height: 800 }).png({ compressionLevel: 9, palette: true, quality: 95 }).toFile(resolve(here, '../../../assets/brand/max-gym-logo-print.png'));
report.push('assets/brand/max-gym-logo-print.png');

console.log(report.join('\n'));
